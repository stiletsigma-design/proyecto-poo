    private void btnAbrirVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirVentaActionPerformed
        int fila = tblVentas.getSelectedRow();

        if (fila == -1) {

            JOptionPane.showMessageDialog(this,
                    "Seleccione una venta para abrir.");
            return;
        }

        int filaModelo =
                tblVentas.convertRowIndexToModel(fila);

        int codigoVenta = Integer.parseInt(
                modelo.getValueAt(filaModelo, 0).toString());

        frm_venta formulario = new frm_venta();

        formulario.cargarVenta(codigoVenta);

        formulario.setLocationRelativeTo(null);
        formulario.setVisible(true);
    }//GEN-LAST:event_btnAbrirVentaActionPerformed

